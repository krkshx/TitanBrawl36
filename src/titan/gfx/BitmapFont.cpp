    static std::size_t decode(const std::string &s, std::size_t i, unsigned &cp) {
        unsigned char c0 = static_cast<unsigned char>(s[i]);
        if (c0 < 0x80) {
            cp = c0;
            return i + 1;
        }
        if ((c0 & 0xE0) == 0xC0 && i + 1 < s.size()) {
            unsigned char c1 = static_cast<unsigned char>(s[i + 1]);
            cp = (static_cast<unsigned>(c0 & 0x1F) << 6) | (c1 & 0x3F);
            return i + 2;
        }
        if ((c0 & 0xF0) == 0xE0 && i + 2 < s.size()) {
            unsigned char c1 = static_cast<unsigned char>(s[i + 1]);
            unsigned char c2 = static_cast<unsigned char>(s[i + 2]);
            cp = (static_cast<unsigned>(c0 & 0x0F) << 12) | (static_cast<unsigned>(c1 & 0x3F) << 6) | (c2 & 0x3F);
            return i + 3;
        }
        cp = 63;
        return i + 1;
    }
    static int measure(const std::string &text) {
        int n = 0;
        std::size_t i = 0;
        while (i < text.size()) {
            unsigned cp = 0;
            i = decode(text, i, cp);
            n++;
        }
        if (n == 0) {
            return 0;
        }
        return n * 6 - 1;
    }
    static void drawText(std::vector<std::uint32_t> &frame, int w, int h, const std::string &text, int x0, int y0, int scale, std::uint32_t color) {
        if (scale < 1) {
            scale = 1;
        }
        unsigned sr = (color >> 16) & 0xFF;
        unsigned sg = (color >> 8) & 0xFF;
        unsigned sb = color & 0xFF;
        unsigned sa = (color >> 24) & 0xFF;
        int x = x0;
        std::size_t i = 0;
        while (i < text.size()) {
            unsigned cp = 0;
            i = decode(text, i, cp);
            const std::uint8_t *g = glyph(cp);
            for (int r = 0; r < 7; r++) {
                std::uint8_t bits = g[r];
                for (int c = 0; c < 5; c++) {
                    if ((bits >> (4 - c)) & 1) {
                        for (int sy = 0; sy < scale; sy++) {
                            for (int sx = 0; sx < scale; sx++) {
                                int px = x + c * scale + sx;
                                int py = y0 + r * scale + sy;
                                if (px >= 0 && px < w && py >= 0 && py < h) {
                                    std::uint32_t dst = frame[static_cast<std::size_t>(py) * static_cast<std::size_t>(w) + static_cast<std::size_t>(px)];
                                    unsigned dr = (dst >> 16) & 0xFF;
                                    unsigned dg = (dst >> 8) & 0xFF;
                                    unsigned db = dst & 0xFF;
                                    unsigned r2 = (sr * sa + dr * (255 - sa)) / 255;
                                    unsigned g2 = (sg * sa + dg * (255 - sa)) / 255;
                                    unsigned b2 = (sb * sa + db * (255 - sa)) / 255;
                                    frame[static_cast<std::size_t>(py) * static_cast<std::size_t>(w) + static_cast<std::size_t>(px)] = 0xFF000000u | (r2 << 16) | (g2 << 8) | b2;
                                }
                            }
                        }
                    }
                }
            }
            x += 6 * scale;
        }
    }
