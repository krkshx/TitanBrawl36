#!/usr/bin/env python3
"""Generate pending LogicCommand subclasses + factory from data/command_table.csv.

Mirrors LogicCommandManager::createCommand (0x7c41d8). Subclass BODIES are
pending reverse: overrides throw pending_reverse until their wave lands;
the base prefix (LogicCommand::encode/decode) is real.

Run:  python tools/generate_commands.py
Out:  titan/gen/LogicCommands.cpp (CPP-only: decls + inline defs)
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    rows = []
    with open(os.path.join(ROOT, "data", "command_table.csv")) as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "," not in line:
                continue
            t, c = line.split(",", 1)
            if not t.strip().lstrip("-").isdigit():
                continue
            rows.append((int(t.strip()), c.strip()))

    # Classes with handwritten bodies (titan/commands/) are skipped here;
    # the factory still covers them via HANDWRITTEN below.
    done = set()
    done_path = os.path.join(ROOT, "data", "commands_done.txt")
    if os.path.exists(done_path):
        with open(done_path, encoding="utf-8") as fh:
            for line in fh:
                line = line.strip()
                if line and not line.startswith("#"):
                    done.add(line)

    gen_src = os.path.join(ROOT, "titan", "gen")
    os.makedirs(gen_src, exist_ok=True)

    with open(os.path.join(gen_src, "LogicCommands.cpp"), "w",
              encoding="utf-8", newline="\n") as fh:
        fh.write("""#pragma once

// Generated by tools/generate_commands.py — do not edit by hand.
// Mirrors LogicCommandManager::createCommand (0x7c41d8).
// Subclass bodies throw pending_reverse until reversed; edit the generator
// output only by re-running after adding real bodies elsewhere.
// CPP-only: declarations + inline definitions in one TU (includable).

#include "titan/commands/LogicCommand.cpp"

#include <memory>

namespace titan {

std::unique_ptr<LogicCommand> createCommandByType(int type);

// Manager shapes (encode @0x85e668 / decode @0x38a110;
// single encodeCommand @0x870160 / decodeCommand @0x2b856c).
void encodeCommandList(ByteStream& s,
                       const std::vector<std::unique_ptr<LogicCommand>>& cmds);
void decodeCommandList(ByteStream& s,
                       std::vector<std::unique_ptr<LogicCommand>>& cmds);
void encodeSingleCommand(ByteStream& s, const std::unique_ptr<LogicCommand>& c);
std::unique_ptr<LogicCommand> decodeSingleCommand(ByteStream& s);

""")
        for t, c in rows:
            if c == "LogicCommand":
                continue  # base itself (type 511); see below
            if c in done:
                continue  # handwritten real body in titan/commands/
            fh.write("class %s : public LogicCommand {\n"
                     "public:\n"
                     "    int getCommandType() const override { return %d; }\n"
                     "    void encode(ByteStream&) const override {\n"
                     "        throw pending_reverse(\"%s pending reverse\");\n"
                     "    }\n"
                     "    void decode(ByteStream&) override {\n"
                     "        throw pending_reverse(\"%s pending reverse\");\n"
                     "    }\n"
                     "};\n\n" % (c, t, c, c))
        fh.write("// Type 511 instantiates the base vtable in the binary.\n"
                 "class LogicCommandBase511 : public LogicCommand {\n"
                 "public:\n"
                 "    int getCommandType() const override { return 511; }\n"
                 "};\n\n} // namespace titan\n\n")
        import glob as _glob
        fh.write("// All command classes (handwritten, one .cpp per class).\n")
        for path in sorted(_glob.glob(os.path.join(
                ROOT, "titan", "commands", "*", "Logic*Command.cpp"))):
            rel = os.path.relpath(path, ROOT)
            fh.write('#include "%s"\n' % rel)
        fh.write("\nnamespace titan {\n\n"
                 "inline std::unique_ptr<LogicCommand> createCommandByType(int type) {\n"
                 "    switch (type) {\n")
        for t, c in rows:
            target = "LogicCommandBase511" if c == "LogicCommand" else c
            fh.write("        case %d: return std::make_unique<%s>();\n" % (t, target))
        fh.write("        default: return nullptr;\n"
                 "    }\n"
                 "}\n\n"
                 "inline void encodeCommandList(ByteStream& s,\n"
                 "                       const std::vector<std::unique_ptr<LogicCommand>>& cmds) {\n"
                 "    s.writeVInt(static_cast<i32>(cmds.size()));\n"
                 "    for (const auto& c : cmds) encodeSingleCommand(s, c);\n"
                 "}\n\n"
                 "inline void decodeCommandList(ByteStream& s,\n"
                 "                       std::vector<std::unique_ptr<LogicCommand>>& cmds) {\n"
                 "    const i32 n = s.readVInt();\n"
                 "    cmds.clear();\n"
                 "    for (i32 i = 0; i < n; ++i) cmds.push_back(decodeSingleCommand(s));\n"
                 "}\n\n"
                 "inline void encodeSingleCommand(ByteStream& s, const std::unique_ptr<LogicCommand>& c) {\n"
                 "    if (!c) throw std::runtime_error(\"null command\");\n"
                 "    s.writeVInt(c->getCommandType());\n"
                 "    c->encode(s);\n"
                 "}\n\n"
                 "inline std::unique_ptr<LogicCommand> decodeSingleCommand(ByteStream& s) {\n"
                 "    auto c = createCommandByType(s.readVInt());\n"
                 "    if (!c) throw std::runtime_error(\"unknown command type\");\n"
                 "    c->decode(s);\n"
                 "    return c;\n"
                 "}\n\n} // namespace titan\n")
    print(f"commands: {len(rows)}")


if __name__ == "__main__":
    main()
